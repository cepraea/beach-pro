import assert from 'node:assert/strict';
import { applyTranslations, CLASSIFICATION, contractProjection, freezeSegments, hasJapanese, restoreProtected, segmentMarkdown, sha256, structuralProjection } from '../engine.mjs';

const profile = { protected_literals: ['lead', 'opus', 'Read'], allowed_japanese_residual: false };
const source = Buffer.from('---\nname: lead\ndescription: 全体を管理する\ntools:\n  - Read\nmodel: opus\n---\n\n# 見出し\n\n本文。\n', 'utf8');
const run = segmentMarkdown({ sourceBuffer: source, runId: 'TRUN-TEST-001', profile });
assert.equal(run.errors.length, 0);
assert.equal(run.segments[0].source_byte_start, 0);
assert.equal(run.segments.at(-1).source_byte_end, source.length);
assert.equal(run.segments.some((s) => s.classification === CLASSIFICATION.PROTECTED_EXACT), true);
assert.equal(run.segments.some((s) => s.classification === CLASSIFICATION.TRANSLATABLE_CONTROLLED), true);
const frozen = freezeSegments(run.segments, run.sourceText);
assert.notEqual(frozen, run.sourceText);
const restored = restoreProtected({ translatedText: frozen, segments: run.segments });
assert.equal(restored.errors.length, 0);
assert.equal(restored.output, run.sourceText);
assert.equal(sha256(Buffer.from(restored.output)), sha256(source));
assert.equal(contractProjection(restored.output).name, 'lead');
assert.deepEqual(contractProjection(restored.output).tools, ['Read']);
assert.equal(structuralProjection(restored.output).headings.length, 1);
assert.equal(hasJapanese('Português brasileiro'), false);
assert.equal(hasJapanese('日本語'), true);
const translations = Object.fromEntries(run.segments.filter((s) => s.classification === CLASSIFICATION.TRANSLATABLE_CONTROLLED).map((s) => [s.segment_id, Buffer.from(s.source_value_base64, 'base64').toString('utf8').replace('全体を管理する', 'Gerencia o conjunto').replace('見出し', 'Título').replace('本文。', 'Texto.') ]));
const applied = applyTranslations({ frozenText: frozen, segments: run.segments, translations });
assert.equal(applied.errors.length, 0);
const translatedRestored = restoreProtected({ translatedText: applied.output, segments: run.segments });
assert.equal(translatedRestored.errors.length, 0);
assert.equal(contractProjection(translatedRestored.output).name, 'lead');
assert.equal(hasJapanese(translatedRestored.output), false);
const invalid = segmentMarkdown({ sourceBuffer: Buffer.from('```text\nsem fechamento\n', 'utf8'), runId: 'TRUN-TEST-002', profile });
assert.equal(invalid.errors.includes('E_PARSE_FAILED'), true);
const duplicate = restoreProtected({ translatedText: `${frozen}${run.segments.find((s) => s.placeholder_id)?.placeholder_id}`, segments: run.segments });
assert.equal(duplicate.errors.some((e) => e.code === 'E_PLACEHOLDER_DUPLICATED'), true);
console.log('translation tests: 20 assertions PASS');
